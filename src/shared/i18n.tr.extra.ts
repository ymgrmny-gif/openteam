export function trDynamicUi(source: string, translate: (text: string, lang: 'tr' | 'en' | 'zh-CN') => string): string | undefined {
  const s = source
  let m: RegExpMatchArray | null
  if ((m = s.match(/^(\d+) 个群聊 · (\d+) 个人员库人员$/))) return `${m[1]} sohbet · ${m[2]} kayıtlı rol`
  if ((m = s.match(/^协作群聊模式 · (\d+) 位成员 · (\d+) 条消息$/))) return `Ortak çalışma · ${m[1]} üye · ${m[2]} mesaj`
  if ((m = s.match(/^独立专家模式 · (\d+) 位成员 · (\d+) 条消息$/))) return `Bağımsız değerlendirme · ${m[1]} üye · ${m[2]} mesaj`
  if ((m = s.match(/^成员 (\d+)$/))) return `Üyeler: ${m[1]}`
  if ((m = s.match(/^(\d+) 人员 · 当前：(.+)$/))) return `${m[1]} rol · Şu an: ${m[2]}`
  if ((m = s.match(/^(\d+) 个角色$/))) return `${m[1]} rol`
  if ((m = s.match(/^(\d+) 个人员$/))) return `${m[1]} rol`
  if ((m = s.match(/^(\d+) 人员$/))) return `${m[1]} rol`
  if ((m = s.match(/^(\d+) 人$/))) return `${m[1]} kişi`
  if ((m = s.match(/^已读 (\d+) 条$/))) return `${m[1]} mesaj okundu`
  if ((m = s.match(/^默认模型：(.+)$/))) return `Varsayılan model: ${m[1]}`
  if ((m = s.match(/^适用：(.+)$/))) return `Kimler için: ${m[1]}`
  if ((m = s.match(/^编辑人员：(.+)$/))) return `Rolü düzenle: ${m[1]}`
  if ((m = s.match(/^已删除群聊 (.+)$/))) return `Silinmiş sohbet: ${m[1]}`
  if ((m = s.match(/^第 (\d+) 步$/))) return `${m[1]}. adım`
  if ((m = s.match(/^节点 (\d+) \/ (\d+)$/))) return `Adım ${m[1]}/${m[2]}`
  if ((m = s.match(/^端口 (\d+)，仅允许本机连接。(?:开启后本机工具可创建群聊并发送任务。)?$/))) return `Bağlantı noktası: ${m[1]}. Yalnız bu bilgisayardan erişilebilir.${s.includes('开启后') ? ' Etkinleştirildiğinde yerel araçlar sohbet oluşturabilir ve görev gönderebilir.' : ''}`
  if ((m = s.match(/^已连接 OpenTeam CLI daemon（端口 (\d+)）。本机工具可以创建群聊并发送任务。$/))) return `OpenTeam yerel servisine bağlandı (port ${m[1]}). Yerel araçlar sohbet oluşturup görev gönderebilir.`
  if ((m = s.match(/^正在连接 OpenTeam CLI daemon（端口 (\d+)）。$/))) return `OpenTeam yerel servisine bağlanılıyor (port ${m[1]}).`
  if ((m = s.match(/^未连接 OpenTeam CLI daemon（端口 (\d+)）。请安装 OpenTeam CLI，或运行 openteamcli daemon start 启动守护进程。$/))) return `OpenTeam yerel servisine bağlanılamadı (port ${m[1]}). OpenTeam CLI kurulumunu ve servisin çalıştığını kontrol edin.`
  if ((m = s.match(/^没有匹配的(内置|自定义)人员$/))) return `Eşleşen ${m[1] === '内置' ? 'hazır' : 'özel'} rol bulunamadı`
  if ((m = s.match(/^暂无(内置|自定义)人员$/))) return `Henüz ${m[1] === '内置' ? 'hazır' : 'özel'} rol yok`
  if ((m = s.match(/^当前分类暂无(内置|自定义)人员$/))) return `Bu kategoride ${m[1] === '内置' ? 'hazır' : 'özel'} rol bulunmuyor`
  if ((m = s.match(/^引用 (.+)：(.+)$/))) return `${m[1]} adlı kişinin yanıtından alıntı: ${m[2]}`
  if ((m = s.match(/^高亮颜色：(.+)$/))) return `Vurgu rengi: ${translate(m[1], 'tr')}`
  if ((m = s.match(/^将发送给：(.+)；正在连接：(.+)$/))) return `Gönderilecek: ${m[1]} · Bağlanılıyor: ${m[2]}`
  if ((m = s.match(/^将发送给：(.+)；跳过正在回复：(.+)$/))) return `Gönderilecek: ${m[1]} · Yanıtlamakta olanlar atlanacak: ${m[2]}`
  if ((m = s.match(/^(.+)：$/))) return `${translate(m[1], 'tr')}:`
  if (s.includes(' · ')) {
    const parts=s.split(' · ').map(part => translate(part,'tr'))
    if (parts.some((part,i)=>part!==s.split(' · ')[i])) return parts.join(' · ')
  }
  return undefined
}
